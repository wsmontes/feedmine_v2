#!/usr/bin/env bash
# FeedMine acceptance-benchmark runner (baseline 1.0).
#
# It is the evaluator's own script, not the product's: it builds the app the way a reader would get it, swaps in
# the corpus's catalogue and the local transport, drives the journey through the real app, and hands the raw
# remains (the app's database, the transport's request log, screenshots) to the frozen oracle. It never edits
# product sources, never shortens a trace, and refuses to run when its own files no longer match the manifest.
#
#   bench/run.sh --gate B01 --profile A [--profile B]
#   bench/run.sh --gate B03 --full-trace
#
# With no device named, the run uses a simulator of its own — created if needed and reused afterwards — and the
# build it installs carries the corpus catalogue under an exclusive bundle identifier
# (com.feedmine.development.benchmark, in every path, dedicated device or not), so the product identifier is left
# holding whatever a product evaluation should launch. Every run prints, at the end and on failure, the exact
# commands that put the product build back.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
# The device this run uses. An operator who names one keeps it: FEEDMINE_BENCH_DEVICE (a simulator by name) or
# FEEDMINE_BENCH_DEVICE_UDID (a physical device, or a simulator by UDID). Naming is a choice, and a choice is
# honoured; the dedicated device below only serves the unnamed case, which used to mean "whatever is booted".
NAMED_DEVICE="${FEEDMINE_BENCH_DEVICE:-}"
# `FEEDMINE_BENCH_DEVICE=booted` names no device either: it means "whatever is booted", which is exactly the case
# the dedicated device below exists for.
if [[ "$NAMED_DEVICE" == "booted" ]]; then
  NAMED_DEVICE=""
fi
DEVICE="${NAMED_DEVICE:-iPhone 17 Pro Max}"
# The product's identifier: what a person's product evaluation launches, and what this run must never install.
BUNDLE_ID="com.feedmine.development"
# The identifier the *instrumented* build carries while the benchmark runs (review 2026-10-11, round 5 item 4). The
# dedicated device reduced the contamination risk, but it left the shared-device path (FEEDMINE_BENCH_SHARED_DEVICE=1)
# naming the product identifier, and a printed reinstall hint was never isolation: the instrumented build was
# installed as $BUNDLE_ID, with the corpus catalogue inside it, and stayed there for the next product evaluation.
# The built product's CFBundleIdentifier is rewritten below and every simctl/devicectl address in this file names
# $BENCH_BUNDLE_ID, in both paths — so a run installs nothing under $BUNDLE_ID that an evaluation could launch.
BENCH_BUNDLE_ID="com.feedmine.development.benchmark"
# The simulator an unnamed run creates or reuses, so the instrumented build never lands on a shared device, plus
# the escape hatch back to the old behaviour.
BENCH_DEVICE_NAME="${FEEDMINE_BENCH_DEVICE_NAME:-FeedMine Bench}"
SHARED_DEVICE="${FEEDMINE_BENCH_SHARED_DEVICE:-0}"
BENCH_DEVICE_UDID=""
# What `simctl` addresses. `booted` is right only when exactly one simulator is booted, which a dedicated device
# would break, so the dedicated path addresses the device by UDID instead.
SIM_TARGET="booted"
SIM_FALLBACK=""
# A physically attached device is named by UDID, because a device destination is identified by `platform:iOS,id:`
# while a simulator one is identified by name. Everything that a device needs differently is guarded by MODE, so
# the simulator path stays exactly the path it ran before.
DEVICE_UDID="${FEEDMINE_BENCH_DEVICE_UDID:-}"
if [[ -n "$DEVICE_UDID" ]]; then
  MODE="device"
  DESTINATION="platform=iOS,id=$DEVICE_UDID"
  # The corpus a device can reach: the same frozen bytes, with every transport reference rewritten to an address
  # that is not the device's own loopback. Generated by bench/transport_variant.py and verified by reversal.
  CORPUS_DIR="bench/device/corpus"
  TRANSPORT_HOST="${FEEDMINE_BENCH_TRANSPORT_HOST:-}"
  [[ -n "$TRANSPORT_HOST" ]] || { echo "FEEDMINE_BENCH_TRANSPORT_HOST is required in device mode (host:port of this Mac on the LAN)"; exit 2; }
else
  MODE="simulator"
  DESTINATION="platform=iOS Simulator,name=$DEVICE"
  CORPUS_DIR="bench/corpus"
  TRANSPORT_HOST="127.0.0.1:8757"
  SIM_FALLBACK="$DEVICE"
fi
# One description of the device for the identity file, the report and the restore command, in both modes.
DEVICE_DESCRIPTION="${BENCH_DEVICE_UDID:-${DEVICE_UDID:-$DEVICE}}"
# One namespace per profile: the second profile's journey must meet the app the way a different reader would,
# never the state the first one left behind.
NAMESPACE_A="${FEEDMINE_BENCH_NAMESPACE:-$(uuidgen)}"
NAMESPACE_B="${FEEDMINE_BENCH_NAMESPACE_B:-$(uuidgen)}"
STAMP="$(date -u +%Y%m%dT%H%M%SZ)"
OUT="$ROOT/bench/run/$STAMP"  # absolute: the driver receives paths, not a shell CWD
GATES=()
PROFILES=()
FULL_TRACE=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --gate) GATES+=("$2"); shift 2 ;;
    --profile) PROFILES+=("$2"); shift 2 ;;
    --full-trace) FULL_TRACE=1; shift ;;
    *) echo "unknown argument: $1"; exit 2 ;;
  esac
done
[[ ${#GATES[@]} -gt 0 ]] || { echo "usage: bench/run.sh --gate B01|B02|B03 [--profile A] [--full-trace]"; exit 2; }
# The list is exactly what was asked for: `--profile A --profile B` used to become A, A, B — the second A ran on
# the same namespace as the first, met its own answers and left a phase record that contradicted the log.
[[ ${#PROFILES[@]} -gt 0 ]] || PROFILES=("A")
mkdir -p "$OUT"

# 1. The benchmark's own files are frozen: a run against an edited evaluator is not a run.
if [[ -f bench/MANIFEST.sha256 ]]; then
  (cd bench && shasum -a 256 -c MANIFEST.sha256 > "$OUT/manifest.check" 2>&1) \
    || { echo "REFUSED: the benchmark files no longer match bench/MANIFEST.sha256"; cat "$OUT/manifest.check"; exit 3; }
  echo "manifest: OK"
else
  echo "REFUSED: bench/MANIFEST.sha256 is missing — freeze the corpus and the evaluator first"; exit 3
fi

# 1a. On the device path the frozen corpus is not what the app can reach: the transport variant is, and it has its
# own manifest. A variant that no longer matches its own hashes is not a variant, and a run against one would be
# a run against an unknown corpus.
if [[ "$MODE" == "device" ]]; then
  if [[ -f bench/device/MANIFEST.sha256 ]]; then
    (cd bench/device && shasum -a 256 -c MANIFEST.sha256 > "$OUT/variant.check" 2>&1) \
      || { echo "REFUSED: the transport variant no longer matches bench/device/MANIFEST.sha256"; cat "$OUT/variant.check"; exit 3; }
    echo "variant: OK"
  else
    echo "REFUSED: bench/device/MANIFEST.sha256 is missing — generate the variant with bench/transport_variant.py"; exit 3
  fi
fi

# 1b. The evaluator's own files are frozen too: a driver or oracle edited while looking at results would be the
# one manipulation this benchmark exists to catch.
if [[ -f bench/EVALUATOR.sha256 ]]; then
  (cd "$ROOT" && shasum -a 256 -c bench/EVALUATOR.sha256 > "$OUT/evaluator.check" 2>&1) \
    || { echo "REFUSED: the evaluator's own files changed since bench/EVALUATOR.sha256"; cat "$OUT/evaluator.check"; exit 3; }
  echo "evaluator: OK"
else
  echo "REFUSED: bench/EVALUATOR.sha256 is missing — freeze the runner, oracle and driver first"; exit 3
fi

# 1c. The host volume is an input of the run. A gate writes a database, a trace, every image the feed prepared,
# and about a gigabyte of build products, and the volume is the one the machine uses for everything else. A full
# disk is not a verdict about the feed: measured 2026-10-10, 464 MB free made `-[NSConcreteFileHandle writeData:]`
# raise `NSFileHandleOperationException` (ENOSPC) inside the app's own trace writer, which aborted the app at 228 s
# of a thirty-minute gate and made it read as FAIL for lack of space rather than for lack of content.
FREE_KB="$(df -k "$ROOT" | awk 'NR==2 {print $4}')"
if [[ "${FREE_KB:-0}" -lt 3145728 ]]; then
  echo "REFUSED: the host volume has $(( ${FREE_KB:-0} / 1024 )) MB free; a gate needs about 3 GB"
  exit 5
fi
echo "free space: $(( FREE_KB / 1024 )) MB"

# 1d. The instrumented build must not land on the device a person uses for product evaluation. `xcodebuild test`
# installs the app it built — with the corpus catalogue inside it — under the identifier that app declares, and
# nothing removed it afterwards: measured 2026-10-11, a later manual evaluation silently ran the benchmark build,
# whose transport is a server that only exists during a run, so the reader appeared to publish nothing. Two
# measures, both of them needed: an unnamed run owns a simulator of its own, created once and reused, and the
# instrumented build carries the exclusive $BENCH_BUNDLE_ID (step 3), so even a shared device
# (FEEDMINE_BENCH_SHARED_DEVICE=1) or a named one keeps the product identifier untouched. Naming a device
# (FEEDMINE_BENCH_DEVICE / FEEDMINE_BENCH_DEVICE_UDID) still keeps the old choice of device.
resolve_bench_device() {
  # Everything this function prints to stdout is the device's UDID, and nothing else: diagnostics go to stderr,
  # because stdout is captured by the caller.
  local line udid device_type runtime
  # The python below is deliberately comment-free: bash 3.2.57 (the bash macOS ships) misparses a "#" comment that
  # contains an apostrophe when it sits inside a heredoc nested in `$( )`, so the explanation lives out here.
  #
  # It reuses the device of that name if one exists, because the run's device must be the same device across
  # interrupted runs and a second one would cost its own gigabytes of simulator data. Otherwise it models the
  # device on the one this run would have used — same device type, same runtime — so the gates measure the hardware
  # profile they measured before.
  line="$(python3 - "$BENCH_DEVICE_NAME" "$DEVICE" <<'PY'
import json, subprocess, sys
name, template = sys.argv[1], sys.argv[2]
try:
    devices = json.loads(subprocess.check_output(["xcrun", "simctl", "list", "devices", "--json"], text=True))["devices"]
except Exception as error:
    print(f"REFUSED: xcrun simctl list devices --json failed: {error}", file=sys.stderr)
    sys.exit(1)
for entries in devices.values():
    for entry in entries:
        if entry["name"] == name and entry.get("isAvailable", True):
            print("reuse", entry["udid"]); sys.exit(0)
for runtime, entries in sorted(devices.items(), reverse=True):
    for entry in entries:
        if entry["name"] == template and entry.get("isAvailable", True):
            print("create", entry["deviceTypeIdentifier"], runtime); sys.exit(0)
sys.exit(1)
PY
)" || { echo "REFUSED: could not resolve a simulator for '$BENCH_DEVICE_NAME' (see above); name one with FEEDMINE_BENCH_DEVICE" >&2; exit 4; }
  case "$line" in
    reuse\ *) udid="${line#reuse }" ;;
    create\ *)
      device_type="${line#create }"; device_type="${device_type%% *}"
      runtime="${line##* }"
      udid="$(xcrun simctl create "$BENCH_DEVICE_NAME" "$device_type" "$runtime")"
      echo "created the simulator '$BENCH_DEVICE_NAME' ($udid) for this run" >&2
      ;;
    *) echo "REFUSED: could not resolve the simulator '$BENCH_DEVICE_NAME'" >&2; exit 4 ;;
  esac
  # An already booted device is the normal case: `boot` refuses it, and `bootstatus` then just reports it ready.
  xcrun simctl boot "$udid" >/dev/null 2>&1 || true
  xcrun simctl bootstatus "$udid" -b >/dev/null 2>&1 || true
  echo "$udid"
}

if [[ "$MODE" == "simulator" && -z "$NAMED_DEVICE" && "$SHARED_DEVICE" != "1" ]]; then
  BENCH_DEVICE_UDID="$(resolve_bench_device)"
  SIM_TARGET="$BENCH_DEVICE_UDID"
  SIM_FALLBACK="$BENCH_DEVICE_NAME"
  DESTINATION="platform=iOS Simulator,id=$BENCH_DEVICE_UDID"
  DEVICE_DESCRIPTION="$BENCH_DEVICE_NAME ($BENCH_DEVICE_UDID, dedicated to the benchmark)"
  echo "device: $DEVICE_DESCRIPTION — the shared simulator is left untouched"
fi

# What this run installs is not what a reader should evaluate. The corpus catalogue lives in the build installed
# under the exclusive $BENCH_BUNDLE_ID, and outside a run the transport that build needs does not exist, so the
# commands to put the product build back under $BUNDLE_ID are printed when the run ends — and when it fails, which
# is exactly when they are easy to lose. A run never installs anything under $BUNDLE_ID ($BENCH_BUNDLE_ID is the
# instrumented build's identity); the product build still has to be reinstalled there for a product evaluation,
# because what that identifier holds is whatever the last product build put there.
print_restore_command() {
  local reason="$1" product_derived="/tmp/feedmine-product-derived"
  local product_app="$product_derived/Build/Products/Debug-iphonesimulator/FeedMine.app"
  echo
  echo "RESTORE THE PRODUCT BUILD ($reason)"
  echo "  this run installed the instrumented build as $BENCH_BUNDLE_ID (never as $BUNDLE_ID) on: $DEVICE_DESCRIPTION"
  echo "  $BUNDLE_ID still holds whatever was installed there before this run, so reinstall the product build:"
  echo "    xcodebuild -project FeedMineApp/FeedMineApp.xcodeproj -scheme FeedMine -destination '$DESTINATION' -derivedDataPath $product_derived build"
  if [[ "$MODE" == "device" ]]; then
    echo "    xcrun devicectl device install app --device $DEVICE_UDID $product_app"
    echo "  on the device there is no host view of the bundle: verify the product build itself"
    echo "    scripts/verify_product_catalogue.sh $product_app"
    echo "  the instrumented build under $BENCH_BUNDLE_ID is not the product; it can be removed with"
    echo "    xcrun devicectl device uninstall app --device $DEVICE_UDID $BENCH_BUNDLE_ID"
  else
    echo "    xcrun simctl install $SIM_TARGET $product_app"
    echo "  then prove the device carries the product catalogue (exit 0), not the corpus (exit 1)"
    echo "    scripts/verify_product_catalogue.sh \"\$(xcrun simctl get_app_container $SIM_TARGET $BUNDLE_ID app)\""
    echo "  the instrumented build under $BENCH_BUNDLE_ID is not the product; it can be removed with"
    echo "    xcrun simctl uninstall $SIM_TARGET $BENCH_BUNDLE_ID"
  fi
}

SERVER_PID=""
trap 'status=$?; kill "${SERVER_PID:-}" 2>/dev/null || true; if [[ $status -ne 0 ]]; then print_restore_command "the run failed with exit $status" >&2; fi' EXIT

# 2. The run's identity, so a result can be audited later.
{
  echo "stamp: $STAMP"
  echo "commit: $(git rev-parse HEAD)"
  echo "dirty: $(git status --porcelain | wc -l | tr -d ' ') files"
  git status --porcelain | head -40
  echo "device: $DEVICE_DESCRIPTION"
  xcrun simctl list devices | grep -F "${BENCH_DEVICE_UDID:-$DEVICE}" || true
  echo "shared device: $SHARED_DEVICE (an unnamed run owns '$BENCH_DEVICE_NAME' unless FEEDMINE_BENCH_SHARED_DEVICE=1)"
  echo "bundle id: $BENCH_BUNDLE_ID (the instrumented build; $BUNDLE_ID is the product's and this run never installs it)"
  xcodebuild -version
} > "$OUT/identity.txt"
shasum -a 256 "$CORPUS_DIR/catalog.sqlite" "$CORPUS_DIR/items.json" bench/oracle.py \
  FeedMineApp/FeedMineAppTests/DiscoveryBenchmarkTests.swift > "$OUT/inputs.sha256"

# 3. Build the app the way a reader gets it (no special flags), then hand it the benchmark's own inputs.
if [[ "$MODE" == "device" ]]; then
  xcodebuild build-for-testing -project FeedMineApp/FeedMineApp.xcodeproj -scheme FeedMine \
    -destination "$DESTINATION" -allowProvisioningUpdates -derivedDataPath "$OUT/derived" \
    > "$OUT/build.log" 2>&1 || { echo "build failed; see $OUT/build.log"; exit 4; }
else
  xcodebuild build-for-testing -project FeedMineApp/FeedMineApp.xcodeproj -scheme FeedMine \
    -destination "$DESTINATION" -derivedDataPath "$OUT/derived" \
    > "$OUT/build.log" 2>&1 || { echo "build failed; see $OUT/build.log"; exit 4; }
fi
APP="$(find "$OUT/derived/Build/Products" -maxdepth 2 -name 'FeedMine.app' -type d | head -1)"
[[ -n "$APP" ]] || { echo "the built app was not found"; exit 4; }
# The instrumented build must not be installable as $BUNDLE_ID. Xcode installs the app it tests from this bundle,
# taking the identifier the bundle declares, so the exclusive identifier is written into the built product here,
# before anything is installed, and every address below (install, get_app_container, launch, terminate, the
# device's app-data container) names it.
#
# The honest risk, recorded as observed rather than assumed: the UI test driver launches the app under test with a
# plain `XCUIApplication()` (FeedMineAppTests/DiscoveryBenchmarkTests.swift, FeedMineUITests.swift), and the
# .xctestrun this build produced has no identifier to launch it by — measured 2026-10-11 on the .xctestrun of an
# earlier run: the UI test records `UITargetAppPath = __TESTROOT__/Debug-iphonesimulator/FeedMine.app` and no
# `UITargetAppBundleIdentifier`; the only identifiers recorded there are the test hosts (`TestHostBundleIdentifier`,
# com.feedmine.development and …FeedMineUITests.xctrunner). The runner therefore has to read the identifier from
# the bundle at that path, which is why the rewrite above is expected to be the identifier it launches — but that
# launch was NOT executed to confirm it, and it is not assumed in the code: if a future Xcode records the target
# application *by identifier* instead, the launch of the app under test fails. That failure is NOT worked around
# here (no product identifier is restored to make it launch). The check after `xcodebuild test-without-building`
# below then fails the run loudly, because an app under test that is not installed as $BENCH_BUNDLE_ID would leave
# a benchmark build under an identifier a product evaluation could launch. Simulator builds are ad-hoc signed with
# `Info.plist=not bound` (measured on this build), so rewriting the plist does not invalidate the signature; the
# device path re-signs after its own plist edits, below.
plutil -replace CFBundleIdentifier -string "$BENCH_BUNDLE_ID" "$APP/Info.plist" \
  || { echo "REFUSED: could not write CFBundleIdentifier into $APP/Info.plist (see $OUT/build.log)"; exit 4; }
WRITTEN_BUNDLE_ID="$(plutil -extract CFBundleIdentifier raw "$APP/Info.plist" 2>/dev/null || true)"
[[ "$WRITTEN_BUNDLE_ID" == "$BENCH_BUNDLE_ID" ]] \
  || { echo "REFUSED: the built app declares '${WRITTEN_BUNDLE_ID:-nothing}', not the exclusive $BENCH_BUNDLE_ID"; exit 4; }
echo "bundle id: $BENCH_BUNDLE_ID (the instrumented build; the product id $BUNDLE_ID is never installed by this run)"
# The labels the driver reads must be the frozen ones — verified on the copy actually packaged into the test
# bundle, not on the source file. A resource that silently failed to copy, or a corpus that moved under the run,
# would otherwise surface only as a verdict about something else. The variant's copy is byte-identical to the
# frozen one (it is the only oracle input the transport rewrite does not touch), so one comparison serves both modes.
PACKAGED_PROFILES="$(find "$OUT/derived/Build/Products" -name 'profiles.json' -path '*.xctest/*' 2>/dev/null | head -1)"
[[ -n "$PACKAGED_PROFILES" ]] || { echo "REFUSED: profiles.json was not packaged into the test bundle"; exit 3; }
EXPECTED_PROFILES="$(awk '/corpus\/profiles.json$/ {print $1}' bench/MANIFEST.sha256)"
ACTUAL_PROFILES="$(shasum -a 256 "$PACKAGED_PROFILES" | awk '{print $1}')"
[[ "$EXPECTED_PROFILES" == "$ACTUAL_PROFILES" ]] \
  || { echo "REFUSED: the packaged profiles.json does not match the frozen corpus"; \
       echo "  expected $EXPECTED_PROFILES"; echo "  actual   $ACTUAL_PROFILES"; exit 3; }
echo "packaged labels: OK"
# The corpus never reaches the repository: this copies it into the *built* product's bundle, which lives under
# bench/run/<stamp>/derived (deleted when the run ends) and is installed on this run's device. Nothing under
# bench/corpus, bench/device/corpus or the app's sources changes — which is why the product build has to be
# reinstalled on that device (and verified with scripts/verify_product_catalogue.sh) before any product evaluation;
# the restore command is printed when this run ends and when it fails.
cp "$CORPUS_DIR/catalog.sqlite" "$APP/catalog.sqlite"
# The payload and its descriptor are one pair. The app verifies the file the descriptor declares — bytes and
# SHA-256 — so handing it the corpus catalogue under the bootstrap manifest is not "the benchmark's input", it is a
# payload that fails verification, and the run would measure a degraded app without saying so. Measured
# 2026-10-11: it did exactly that. The descriptor written here describes the corpus honestly: its own byte count,
# its own digest, and the source count its own `catalog_metadata` declares, which is what the product's reader
# reports. Revision 5 stays, because the corpus is a slice of revision 5 and says so in that same table.
python3 - "$APP" "$CORPUS_DIR/catalog.sqlite" <<'PY'
import hashlib, json, sqlite3, sys, datetime
app, payload = sys.argv[1], sys.argv[2]
digest = hashlib.sha256()
size = 0
with open(payload, "rb") as handle:
    while chunk := handle.read(1 << 20):
        digest.update(chunk); size += len(chunk)
meta = dict(sqlite3.connect(f"file:{payload}?mode=ro", uri=True).execute("SELECT key, value FROM catalog_metadata"))
manifest = {
    "schemaVersion": 1, "revision": 5,
    "generatedAt": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
    "sourceCount": int(meta["source_count"]), "fileCount": 1,
    "files": [{"path": "catalog.sqlite", "bytes": size, "sha256": digest.hexdigest()}],
}
with open(f"{app}/catalog.manifest.json", "w") as handle:
    json.dump(manifest, handle, indent=1)
print(f"injected the pair: {size} bytes, sha256 {digest.hexdigest()[:16]}, sourceCount {meta['source_count']}")
PY
# The transport is the evaluator's input, never a product change.
#
# On the simulator the app reaches it over cleartext on the loopback address, which is what the runner declared
# before. On a physical device the address is a LAN IP, and since iOS 17 ATS **refuses IP addresses by default**:
# the exception has to name the address, as the key of an NSExceptionDomains entry, without a port — see
# developer.apple.com/documentation/bundleresources/information-property-list/nsapptransportsecurity/nsexceptiondomains
# ("In iOS 17 … ATS no longer allows connections to IP addresses by default. Add individual IP addresses and
# classless inter-domain routing (CIDR) ranges in the NSExceptionDomains dictionary"). `NSAllowsLocalNetworking` is
# kept as the declaration of intent Apple recommends, but its own page is ambiguous about whether it alone covers a
# private IPv4 address, so the address is declared as well. A device also needs the Local Network privilege for an
# outgoing TCP connection to a LAN address (TN3179: "Making an outgoing TCP connection → yes", applied to
# URLSession), hence the usage string — the reader sees one prompt, once.
if [[ "$MODE" == "device" ]]; then
  TRANSPORT_ADDRESS="${TRANSPORT_HOST%%:*}"
  ATS_JSON="{\"NSAllowsLocalNetworking\":true,\"NSExceptionDomains\":{\"$TRANSPORT_ADDRESS\":{\"NSExceptionAllowsInsecureHTTPLoads\":true}}}"
  plutil -replace NSAppTransportSecurity -json "$ATS_JSON" "$APP/Info.plist" 2>/dev/null \
    || plutil -insert NSAppTransportSecurity -json "$ATS_JSON" "$APP/Info.plist"
  LOCAL_NETWORK_TEXT="The benchmark's own transport answers on this network."
  plutil -replace NSLocalNetworkUsageDescription -string "$LOCAL_NETWORK_TEXT" "$APP/Info.plist" 2>/dev/null \
    || plutil -insert NSLocalNetworkUsageDescription -string "$LOCAL_NETWORK_TEXT" "$APP/Info.plist"
  # Mutating a bundle Xcode already signed invalidates its signature, and the device refuses the install with
  # `ApplicationVerificationFailed`, naming the Info.plist rather than the cause. Re-signing with the entitlements
  # the build itself produced is what closes the injection, and re-signing without them makes the profile stop
  # matching. (§67)
  codesign -d --entitlements :- "$APP" > "$OUT/entitlements.plist" 2>/dev/null
  SIGN_ID="${FEEDMINE_BENCH_SIGN_ID:-$(security find-identity -v -p codesigning | awk -F'"' '/Apple Development/ {print $2; exit}')}"
  [[ -n "$SIGN_ID" ]] || { echo "no Apple Development identity found to re-sign with"; exit 4; }
  codesign --force --sign "$SIGN_ID" --entitlements "$OUT/entitlements.plist" "$APP" \
    || { echo "re-signing failed"; exit 4; }
else
  plutil -replace NSAppTransportSecurity -json '{"NSAllowsLocalNetworking":true}' "$APP/Info.plist" 2>/dev/null \
    || plutil -insert NSAppTransportSecurity -json '{"NSAllowsLocalNetworking":true}' "$APP/Info.plist"
fi

# 4. Serve the corpus, and learn its totals before anything is judged. A device has to reach the transport, so on
# the device path the server answers on every interface; loopback is enough for the simulator.
#
# The port is an input of the run. Something already listening there would answer the app and the runner's own
# `curl`, and the log the oracle reads would stay empty while the run looked alive. Measured 2026-10-11: a server
# left running from an earlier session held 8757, the runner's own server never started, and a device run produced
# a verdict about nobody's transport. Refusing is the only honest answer.
if lsof -nP -iTCP:8757 -sTCP:LISTEN >/dev/null 2>&1; then
  echo "REFUSED: something is already listening on 8757, the transport's port"
  lsof -nP -iTCP:8757 -sTCP:LISTEN | tail -2
  exit 5
fi
if [[ "$MODE" == "device" ]]; then
  python3 bench/serve.py --host 0.0.0.0 --port 8757 --corpus "$CORPUS_DIR" --log "$OUT/server.log" > "$OUT/server.out" 2>&1 &
else
  python3 bench/serve.py --port 8757 --corpus "$CORPUS_DIR" --log "$OUT/server.log" > "$OUT/server.out" 2>&1 &
fi
SERVER_PID=$!
# The EXIT trap installed in 1d kills this server (it reads SERVER_PID from here) and, when the run failed, prints
# how to restore the product build.
sleep 1
curl -sf "http://$TRANSPORT_HOST/totals" > "$OUT/totals.json" || { echo "the local transport is not answering"; exit 5; }

# 5. Drive the journey for each gate, with each profile the gate asks for. The B profile is a second half of B01's
# own clause ("another profile changes the consulted sources"), never a substitute for the first.
run_gate() {
  local gate="$1" profile="$2" namespace="$3" log="$4"
  : > "$log"
  # The phase record is rewritten by this run, never appended to a previous one's.
  : > "$OUT/$gate-$profile.phases"
  local only="FeedMineUITests/DiscoveryBenchmarkTests"
  case "$gate" in
    B01) only="$only/testB01DiscoveryWithoutASubscription" ;;
    B02) only="$only/testB02RelevanceAndVariety" ;;
    B03) only="$only/testB03ThirtyMinuteRunway" ;;
    B04) only="$only/testB04PresentedFeedIsSacred" ;;
    B05) only="$only/testB05ContextsReopenOfflineAndSaved" ;;
  esac
  # `TEST_RUNNER_` is how a variable reaches the *test runner* process: xcodebuild does not forward the
  # invoking environment, and the driver runs there (the app under test is given its own environment).
  #
  # There is deliberately no `FEEDMINE_BENCH_CORPUS` here. The driver's only use of the corpus is
  # `profiles.json` — the labels it answers the Composer with — and it now resolves that file from its own test
  # bundle. Passing a host path worked only because a simulator reads the Mac's filesystem; on a device it can
  # never work, and an asymmetry that exists only in one mode is exactly the kind of difference B06 exists to
  # measure. One path, both modes.
  # `FEEDMINE_BENCH_PHASES` is deliberately absent on the device path: the runner names a path on the Mac, and a
  # device has no view of the Mac's filesystem — the driver's `try?` write would fail silently and the oracle would
  # read a phase record that never existed. There the driver writes the record inside its own container and attaches
  # it to the result bundle, and the extraction below deposits it where the oracle already looks. `env` is used
  # rather than a bare assignment prefix so that the variable can be present or absent without an array (bash 3.2
  # treats an empty array as unbound under `set -u`).
  PHASES_ASSIGN=""
  [[ "$MODE" == "device" ]] || PHASES_ASSIGN="TEST_RUNNER_FEEDMINE_BENCH_PHASES=$OUT/$gate-$profile.phases"
  env $PHASES_ASSIGN \
    TEST_RUNNER_FEEDMINE_BENCHMARK=1 \
    TEST_RUNNER_FEEDMINE_BENCH_NAMESPACE="$namespace" \
    TEST_RUNNER_FEEDMINE_BENCH_FULL_TRACE="$FULL_TRACE" \
    TEST_RUNNER_FEEDMINE_BENCH_PROFILE="$profile" \
    xcodebuild test-without-building -project FeedMineApp/FeedMineApp.xcodeproj -scheme FeedMine \
      -destination "$DESTINATION" -derivedDataPath "$OUT/derived" \
      -only-testing:"$only" > "$OUT/$gate-$profile.log" 2>&1 || echo "($gate/$profile: xcodebuild exited non-zero — see $OUT/$gate-$profile.log)"
  if [[ "$MODE" == "device" ]]; then
    # A device has no `simctl`, and the driver's own screenshots are attached to the result bundle instead of
    # being taken from the host. Exporting them keeps the evidence in the same place it has always been, and the
    # phase record rides out with them: it is the one oracle input that has no host path on a device.
    RESULT_BUNDLE="$(ls -dt "$OUT/derived/Logs/Test/"*.xcresult 2>/dev/null | head -1)"
    if [[ -n "$RESULT_BUNDLE" ]]; then
      xcrun xcresulttool export attachments --path "$RESULT_BUNDLE" \
        --output-path "$OUT/$gate-$profile.shots" > "$OUT/$gate-$profile.shots.log" 2>&1 || true
      python3 - "$OUT/$gate-$profile.shots" "$OUT/$gate-$profile.phases" <<'PY' || echo "($gate/$profile: no phase record in the result bundle)"
import json, shutil, sys
shots, destination = sys.argv[1], sys.argv[2]
try:
    manifest = json.load(open(f"{shots}/manifest.json"))
except Exception:
    sys.exit(1)
for entry in manifest:
    for attachment in entry.get("attachments", []):
        name = attachment.get("suggestedHumanReadableName") or ""
        if name.startswith("phases"):
            shutil.copyfile(f"{shots}/{attachment['exportedFileName']}", destination)
            print(f"phase record extracted: {name} -> {destination}")
            sys.exit(0)
sys.exit(1)
PY
    fi
  else
    # The run's own acceptance (round 5, item 4), checked rather than assumed: the app under test must be installed
    # under the exclusive $BENCH_BUNDLE_ID. If the runner could not launch the rewritten identifier — the failure
    # mode the comment on the rewrite above records — nothing is installed there, and the run fails loudly here
    # instead of producing a verdict about an app that never ran. It must never fall back to $BUNDLE_ID: a
    # benchmark build under that identifier is what a later product evaluation would silently launch.
    if xcrun simctl get_app_container "$SIM_TARGET" "$BENCH_BUNDLE_ID" app >/dev/null 2>&1 \
      || xcrun simctl get_app_container "${SIM_FALLBACK:-$SIM_TARGET}" "$BENCH_BUNDLE_ID" app >/dev/null 2>&1; then
      : # installed under the exclusive identifier, as this run requires
    else
      echo "FAIL ($gate/$profile): no app is installed as $BENCH_BUNDLE_ID on $DEVICE_DESCRIPTION" >&2
      echo "  the instrumented build is installed under that exclusive identifier and nowhere else, so the app" >&2
      echo "  under test did not come from this run's rewrite (see the identifier comment above); the gate log:" >&2
      tail -20 "$OUT/$gate-$profile.log" >&2
      exit 6
    fi
    xcrun simctl io "$SIM_TARGET" screenshot "$OUT/$gate-$profile.png" >/dev/null 2>&1 || true
  fi
}

# The oracle judges the app's own database, so the run has to bring it back. On the simulator the container is a
# host directory and the database is read where it lies. On a device there is no host view of the container:
# `devicectl device copy from` addresses it by a path relative to the container, so the pull below never has to
# resolve a container path — and the oracle receives a pulled copy instead of a live file.
container() {
  if [[ "$MODE" == "device" ]]; then
    echo "$OUT/container"
    return
  fi
  # The instrumented build's container, addressed by the exclusive identifier it was installed under: the product
  # identifier may hold the product build, whose database is not this run's measurement.
  xcrun simctl get_app_container "$SIM_TARGET" "$BENCH_BUNDLE_ID" data 2>/dev/null \
    || xcrun simctl get_app_container "${SIM_FALLBACK:-$SIM_TARGET}" "$BENCH_BUNDLE_ID" data
}

for gate in "${GATES[@]}"; do
  for profile in "${PROFILES[@]}"; do
    namespace_var="NAMESPACE_$profile"
    namespace="${!namespace_var:-$NAMESPACE_A}"
    log="$OUT/server.log"
    [[ "$profile" == "B" ]] && log="$OUT/server-b.log"
    run_gate "$gate" "$profile" "$namespace" "$log"
  done
done

# 6. The oracle judges what the run left behind — never what the app said about itself. A device that went away
# mid-run is a missing measurement, not a reason to lose the report: the verdict is NOT_RUN and the reason is in
# the document.
#
# The evidence it needs lives *beside* the runtime database: the app's own trace, which is where B03's stall
# measurement is. Reading it in place worked only for as long as the container survived — and measured 2026-10-11,
# the trace of that B03 run was gone by the time its single stall had to be explained, because reinstalling the app
# replaces the container. The rule the counsellor fixed is "preserve build SHA, hashes, raw trace and the
# classification of every clause": what cannot be reconstructed must not be left where it can be destroyed. Both
# modes now copy the namespace into the run first, and the oracle is handed the copy.
LIVE_CONTAINER="$(container || true)"
PULLED_CONTAINER="$OUT/container"
if [[ "$MODE" == "device" ]]; then
  # A namespace that never ran leaves no database: the pull fails quietly and the oracle reports a missing
  # measurement, which is what that is. The destination keeps the container's shape, so the oracle's paths — which
  # are built from `--database` — are unchanged.
  #
  # A device has no `get_app_container`, so the pull is also where this run can see which identifier the app under
  # test ran under: it asks the exclusive one first, and only when that answers nothing does it ask the product's
  # identifier for the same namespace — a namespace this run minted, which only this run's own app can have written.
  # An answer from there is the isolation having failed, and the run states exactly that instead of reading an
  # instrumented build's database as if it were a product one.
  for namespace in "$NAMESPACE_A" "$NAMESPACE_B"; do
    destination="$PULLED_CONTAINER/Library/Application Support/FeedMine/$namespace"
    mkdir -p "$destination"
    if ! xcrun devicectl device copy from --device "$DEVICE_UDID" --domain-type appDataContainer \
      --domain-identifier "$BENCH_BUNDLE_ID" --source "Library/Application Support/FeedMine/$namespace" \
      --destination "$destination" > "$OUT/container-$namespace.log" 2>&1; then
      leak_probe="$OUT/leak-probe-$namespace"
      rm -rf "$leak_probe"
      if xcrun devicectl device copy from --device "$DEVICE_UDID" --domain-type appDataContainer \
        --domain-identifier "$BUNDLE_ID" --source "Library/Application Support/FeedMine/$namespace" \
        --destination "$leak_probe" > "$OUT/container-$namespace-leak.log" 2>&1; then
        echo "LEAK: the app under test ran under the product identifier $BUNDLE_ID, not $BENCH_BUNDLE_ID" >&2
        echo "  namespace $namespace was found in $BUNDLE_ID's app-data container" >&2
        echo "  (see $OUT/container-$namespace-leak.log); nothing is installed under $BENCH_BUNDLE_ID" >&2
        echo "  (see $OUT/container-$namespace.log): this build carries the corpus catalogue, so the app under that" >&2
        echo "  identifier is the benchmark's, and nothing may be left there for a product evaluation to launch" >&2
        exit 6
      fi
    fi
  done
else
  for namespace in "$NAMESPACE_A" "$NAMESPACE_B"; do
    source_dir="$LIVE_CONTAINER/Library/Application Support/FeedMine/$namespace"
    [[ -d "$source_dir" ]] || continue
    destination="$PULLED_CONTAINER/Library/Application Support/FeedMine/$namespace"
    mkdir -p "$destination"
    cp -R "$source_dir/." "$destination/" > "$OUT/container-$namespace.log" 2>&1 || true
  done
fi
APP_CONTAINER="$PULLED_CONTAINER"
DB="$APP_CONTAINER/Library/Application Support/FeedMine/$NAMESPACE_A/runtime.sqlite"
DB_B="$APP_CONTAINER/Library/Application Support/FeedMine/$NAMESPACE_B/runtime.sqlite"
ARGS=(--run "$OUT" --corpus bench/corpus --database "$DB")
[[ -f "$DB_B" && "$DB_B" != "$DB" ]] && ARGS+=(--database-b "$DB_B")
for gate in "${GATES[@]}"; do
  python3 bench/oracle.py "${ARGS[@]}" --gate "$gate" | tee "$OUT/$gate.verdict.json" || true
done

# 7. One report per run, in the benchmark's own shape. An honest FAIL is the point.
{
  echo "# Run $STAMP"
  echo
  echo "- device: $DEVICE_DESCRIPTION ($MODE) · transport: $TRANSPORT_HOST · corpus: $CORPUS_DIR · commit: $(git rev-parse HEAD) · dirty files: $(git status --porcelain | wc -l | tr -d ' ')"
  echo "- corpus: $(python3 -c 'import json,sys; print(json.dumps(json.load(open("'"$OUT"'/totals.json"))["totals"]))' 2>/dev/null || echo 'totals unavailable')"
  echo "- database: $DB"
  echo
  for gate in "${GATES[@]}"; do
    echo "## $gate — $(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["verdict"])' "$OUT/$gate.json" 2>/dev/null || echo NOT_RUN)"
    echo
    python3 - "$OUT/$gate.json" <<'PY' 2>/dev/null || echo "(no verdict file)"
import json, sys
result = json.load(open(sys.argv[1]))
states = result.get("states")
if states:
    # The review's requirement: the acquisition set, what was actually asked for, and what the reader saw are
    # three different measurements, and a report that conflates them can claim a lot from a single number.
    labels = {"registered_in_the_acquisition_set": "fontes no conjunto de aquisição",
              "contacted_over_the_wire": "fontes efetivamente buscadas",
              "published_sources": "fontes que chegaram aos cards",
              "published_cards": "cards publicados"}
    for key, label in labels.items():
        print(f"- estado — {label}: {states.get(key)}")
for clause in result["clauses"]:
    mark = {True: "PASS", False: "FAIL", None: "NOT_RUN"}[clause["pass"]]
    print(f"- {mark} — {clause['clause']} (observed: {json.dumps(clause['observed'], ensure_ascii=False)})")
PY
    echo
  done
  echo "## Identidade dos insumos"
  cat "$OUT/inputs.sha256"
} > "$OUT/report.md"
# The derived data of a run is rebuildable and costs about a gigabyte per gate: the evidence is the logs, the
# reports, the verdicts and the screenshots, never the build products. Leaving them filled the disk (measured:
# 8.6 GB of runs, 121 MB free) and the next build failed with no space left.
rm -rf "$OUT/derived"
echo "run written to $OUT (report.md)"
print_restore_command "the run finished"
